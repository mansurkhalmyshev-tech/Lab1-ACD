
#include <iostream>       // Подключаем библиотеку для ввода и вывода
#include <string>          // Подключаем библиотеку для работы со строками
#include <vector>          // Подключаем библиотеку для создания списков

using namespace std;       // Чтобы не писать std:: перед командами

// Создаём класс Soldier (Солдат)
class Soldier {
private:                   // Закрытая часть класса
    string rank;           // Звание солдата
    string name;           // Имя солдата
    int experience;        // Опыт службы в годах

    static int soldierCount; // Общий счётчик всех солдат

public:                    // Открытая часть класса

    // Конструктор класса Soldier
    Soldier(string r, string n, int exp) {
        rank = r;          // Записываем звание
        name = n;          // Записываем имя
        experience = exp;  // Записываем опыт

        soldierCount++;    // Увеличиваем количество солдат

        cout << "Создан солдат: " << name << endl; // Выводим сообщение
    }

    // Деструктор класса Soldier
    ~Soldier() {
        soldierCount--;    // Уменьшаем количество солдат

        cout << "Уничтожен солдат: " << name << endl; // Сообщаем об удалении
    }

    // Метод для получения имени солдата
    string getName() {
        return name;       // Возвращаем имя
    }

    // Метод для вывода информации о солдате
    void print() {
        cout << "Звание: " << rank << endl;          // Выводим звание
        cout << "Имя: " << name << endl;             // Выводим имя
        cout << "Опыт: " << experience << " лет" << endl; // Выводим опыт
    }

    // Статический метод для получения количества солдат
    static int getSoldierCount() {
        return soldierCount; // Возвращаем значение счётчика
    }
};

// Объявляем начальное значение статического счётчика
int Soldier::soldierCount = 0;


// Создаём класс Squad (Отряд)
class Squad {
private:                       // Закрытая часть класса
    string squadName;          // Название отряда

    vector<Soldier*> soldiers; // Список указателей на солдат (агрегация)

public:                        // Открытая часть класса

    // Конструктор класса Squad
    Squad(string name) {
        squadName = name;      // Записываем название отряда
        cout << "Создан отряд: " << squadName << endl; // Выводим сообщение
    }

    // Деструктор класса Squad
    ~Squad() {
        cout << "Отряд " << squadName << " расформирован." << endl;
        // Солдаты не удаляются, потому что существуют независимо от отряда
    }

    // Метод добавления солдата в отряд
    void addSoldier(Soldier* soldier) {

        if (soldier == nullptr) { // Проверяем, существует ли указатель
            cout << "Ошибка: солдат не существует!" << endl; // Выводим ошибку
            return;                  // Завершаем метод
        }

        soldiers.push_back(soldier); // Добавляем указатель в список

        cout << soldier->getName()   // Получаем имя солдата
            << " добавлен в отряд." << endl; // Выводим сообщение
    }

    // Метод вывода списка солдат
    void print() {

        cout << "\nОтряд: " << squadName << endl; // Выводим название отряда

        // Перебираем всех солдат в списке
        for (int i = 0; i < soldiers.size(); i++) {

            if (soldiers[i] != nullptr) { // Проверяем указатель

                soldiers[i]->print();     // Выводим информацию о солдате

                cout << "----------------" << endl; // Разделитель
            }
        }
    }
};


// Главная функция программы
int main() {

    setlocale(LC_ALL, "Russian"); // Включаем русский язык в консоли

    cout << "Количество солдат: "
        << Soldier::getSoldierCount() << endl; // В начале солдат 0

    // Создаём трёх солдат независимо от отряда
    Soldier s1("Рядовой", "Иванов", 1);   // Первый солдат
    Soldier s2("Сержант", "Петров", 5);  // Второй солдат
    Soldier s3("Лейтенант", "Сидоров", 8); // Третий солдат

    cout << "\nВсего солдат: "
        << Soldier::getSoldierCount() << endl; // Выводим количество

    { // Начало отдельного блока

        Squad squad("Первый"); // Создаём отряд

        squad.addSoldier(&s1); // Добавляем первого солдата
        squad.addSoldier(&s2); // Добавляем второго солдата
        squad.addSoldier(&s3); // Добавляем третьего солдата

        squad.print();         // Выводим информацию обо всех солдатах

        cout << "\nСолдат в отряде: "
            << Soldier::getSoldierCount() << endl; // Показываем счётчик

    } // Здесь отряд уничтожается, но солдаты остаются

    cout << "\nОтряд уничтожен!" << endl; // Выводим сообщение

    cout << "Солдат осталось: "
        << Soldier::getSoldierCount() << endl; // Всё ещё 3 солдата

    // Проверяем, что солдаты продолжают существовать
    cout << "\nПроверка существования солдат:" << endl;

    s1.print(); // Выводим первого солдата
    s2.print(); // Выводим второго солдата
    s3.print(); // Выводим третьего солдата

    return 0; // Завершаем программу
}
